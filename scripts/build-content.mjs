// Turns content/news/*.md into a typed module the app imports directly.
// Markdown is rendered here, at build time, so no markdown parser ships to the browser.
// Run before `tsc` and `vite build` — see the "build" script in package.json.
import fs from 'node:fs'
import path from 'node:path'
import { loadNews, root } from './content.mjs'

const outDir = path.join(root, 'src', 'content')
const outFile = path.join(outDir, 'news.generated.ts')

const posts = loadNews()

const body = `// AUTO-GENERATED by scripts/build-content.mjs — do not edit by hand.
// Edit the markdown in content/news/ instead, or use the editor at /admin.

export type NewsPost = {
  slug: string
  title: string
  /** ISO date, used for ordering and the sitemap. */
  date: string
  /** What the page actually shows, e.g. "22 May 2026" or "May 2026". */
  dateLabel: string
  summary: string
  /** Path under /uploads, or '' when the post has no image. */
  image: string
  /** Rendered HTML of the post body. */
  html: string
}

export const NEWS: NewsPost[] = ${JSON.stringify(posts, null, 2)}
`

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(outFile, body)
console.log(`Generated ${path.relative(root, outFile)} from ${posts.length} post${posts.length === 1 ? '' : 's'}.`)
